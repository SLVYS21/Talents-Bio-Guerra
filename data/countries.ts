const COUNTRY_BY_ISO = new Map(COUNTRIES.map((c) => [c.iso2, c]));

export function getCountry(iso2: string): Country | undefined {
  return COUNTRY_BY_ISO.get(iso2);
}

export function flagEmoji(iso2: string): string {
  if (!/^[A-Z]{2}$/.test(iso2)) return "🏳️";
  const base = 0x1f1e6;
  const chars = [iso2.charCodeAt(0) - 65 + base, iso2.charCodeAt(1) - 65 + base];
  return String.fromCodePoint(...chars);
}

export function orderedCountries(): Country[] {
  const africanSet = new Set(AFRICAN_ISO);
  const africanInOrder = AFRICAN_ISO
    .map((iso) => COUNTRY_BY_ISO.get(iso))
    .filter(Boolean) as Country[];
  const rest = COUNTRIES
    .filter((c) => !africanSet.has(c.iso2))
    .sort((a, b) => a.nameFr.localeCompare(b.nameFr, "fr"));
  return [...africanInOrder, ...rest];
}

